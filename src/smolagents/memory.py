def _to_json_safe(obj: Any) -> Any:
    """Encode an object with the SafeSerializer, falling back to its string representation for unsupported types."""
    try:
        return SafeSerializer.to_json_safe(obj)
    except (SerializationError, RecursionError):
        return str(obj)


def _chat_message_to_dict(message: ChatMessage | None) -> dict[str, Any] | None:
    if message is None:
        return None
    return {
        "role": MessageRole(message.role).value,
        "content": _to_json_safe(message.content),
        "tool_calls": [_to_json_safe(asdict(tool_call)) for tool_call in message.tool_calls]
        if message.tool_calls
        else None,
        "token_usage": message.token_usage.dict() if message.token_usage else None,
    }


def _chat_message_from_dict(message_dict: dict[str, Any] | None) -> ChatMessage | None:
    if message_dict is None:
        return None
    message_dict = SafeSerializer.from_json_safe(message_dict)
    return ChatMessage.from_dict(message_dict, token_usage=_token_usage_from_dict(message_dict.get("token_usage")))


def _token_usage_from_dict(token_usage_dict: dict[str, int] | None) -> TokenUsage | None:
    if token_usage_dict is None:
        return None
    return TokenUsage(input_tokens=token_usage_dict["input_tokens"], output_tokens=token_usage_dict["output_tokens"])


def _timing_from_dict(timing_dict: dict[str, float | None]) -> Timing:
    return Timing(start_time=timing_dict["start_time"], end_time=timing_dict["end_time"])


@dataclass
class ToolCall:
    name: str
    arguments: Any
    id: str

    def dict(self):
        return {
            "id": self.id,
            "type": "function",
            "function": {
                "name": self.name,
                "arguments": make_json_serializable(self.arguments),
            },
        }


@dataclass
class MemoryStep:
    def dict(self):
        return asdict(self)

    def to_dict(self) -> "dict[str, Any]":
        """Convert the step to a JSON-serializable dictionary that can be restored with `from_dict`.

        Unlike `dict()`, which is meant for display and logging, this keeps images and other supported types intact.
        Values of types that the [`SafeSerializer`] does not support are replaced by their string representation.
        """
        return {field.name: _to_json_safe(getattr(self, field.name)) for field in fields(self)}

    @classmethod
    def from_dict(cls, step_dict: "dict[str, Any]") -> "MemoryStep":
        """Create a step from a dictionary generated by `to_dict`."""
        return cls(**SafeSerializer.from_json_safe(step_dict))

    def to_messages(self, summary_mode: bool = False) -> list[ChatMessage]:
        raise NotImplementedError


@dataclass
class ActionStep(MemoryStep):
    step_number: int
    timing: Timing
    model_input_messages: list[ChatMessage] | None = None
    tool_calls: list[ToolCall] | None = None
    error: AgentError | None = None
    model_output_message: ChatMessage | None = None
    model_output: str | list[dict[str, Any]] | None = None
    code_action: str | None = None
    observations: str | None = None
    observations_images: list["PIL.Image.Image"] | None = None
    action_output: Any = None
    token_usage: TokenUsage | None = None
    is_final_answer: bool = False

    def dict(self):
        # We overwrite the method to parse the tool_calls and action_output manually
        return {
            "step_number": self.step_number,
            "timing": self.timing.dict(),
            "model_input_messages": [
                make_json_serializable(get_dict_from_nested_dataclasses(msg)) for msg in self.model_input_messages
            ]
            if self.model_input_messages
            else None,
            "tool_calls": [tc.dict() for tc in self.tool_calls] if self.tool_calls else [],
            "error": self.error.dict() if self.error else None,
            "model_output_message": make_json_serializable(get_dict_from_nested_dataclasses(self.model_output_message))
            if self.model_output_message
            else None,
            "model_output": self.model_output,
            "code_action": self.code_action,
            "observations": self.observations,
            "observations_images": [image.tobytes() for image in self.observations_images]
            if self.observations_images
            else None,
            "action_output": make_json_serializable(self.action_output),
            "token_usage": asdict(self.token_usage) if self.token_usage else None,
            "is_final_answer": self.is_final_answer,
        }

    def to_dict(self) -> "dict[str, Any]":
        # `model_input_messages` are left out: they duplicate the content of the previous steps
        return {
            "step_number": self.step_number,
            "timing": self.timing.dict(),
            "tool_calls": [_to_json_safe(asdict(tool_call)) for tool_call in self.tool_calls]
            if self.tool_calls is not None
            else None,
            "error": self.error.dict() if self.error else None,
            "model_output_message": _chat_message_to_dict(self.model_output_message),
            "model_output": _to_json_safe(self.model_output),
            "code_action": self.code_action,
            "observations": self.observations,
            "observations_images": _to_json_safe(self.observations_images),
            "action_output": _to_json_safe(self.action_output),
            "token_usage": self.token_usage.dict() if self.token_usage else None,
            "is_final_answer": self.is_final_answer,
        }

    @classmethod
    def from_dict(cls, step_dict: "dict[str, Any]") -> "ActionStep":
        tool_calls = step_dict.get("tool_calls")
        error = step_dict.get("error")
        return cls(
            step_number=step_dict["step_number"],
            timing=_timing_from_dict(step_dict["timing"]),
            tool_calls=[ToolCall(**SafeSerializer.from_json_safe(tool_call)) for tool_call in tool_calls]
            if tool_calls is not None
            else None,
            error=AgentError.from_dict(error) if error else None,
            model_output_message=_chat_message_from_dict(step_dict.get("model_output_message")),
            model_output=SafeSerializer.from_json_safe(step_dict.get("model_output")),
            code_action=step_dict.get("code_action"),
            observations=step_dict.get("observations"),
            observations_images=SafeSerializer.from_json_safe(step_dict.get("observations_images")),
            action_output=SafeSerializer.from_json_safe(step_dict.get("action_output")),
            token_usage=_token_usage_from_dict(step_dict.get("token_usage")),
            is_final_answer=step_dict.get("is_final_answer", False),
        )

    def to_messages(self, summary_mode: bool = False) -> list[ChatMessage]:
        messages = []
        if self.model_output is not None and not summary_mode:
            messages.append(
                ChatMessage(role=MessageRole.ASSISTANT, content=[{"type": "text", "text": self.model_output.strip()}])
            )

        if self.tool_calls is not None:
            messages.append(
                ChatMessage(
                    role=MessageRole.TOOL_CALL,
                    content=[
                        {
                            "type": "text",
                            "text": "Calling tools:\n" + str([tc.dict() for tc in self.tool_calls]),
                        }
                    ],
                )
            )

        if self.observations_images:
            messages.append(
                ChatMessage(
                    role=MessageRole.USER,
                    content=[
                        {
                            "type": "image",
                            "image": image,
                        }
                        for image in self.observations_images
                    ],
                )
            )

        if self.observations is not None:
            messages.append(
                ChatMessage(
                    role=MessageRole.TOOL_RESPONSE,
                    content=[
                        {
                            "type": "text",
                            "text": f"Observation:\n{self.observations}",
                        }
                    ],
                )
            )
        if self.error is not None:
            error_message = (
                "Error:\n"
                + str(self.error)
                + "\nNow let's retry: take care not to repeat previous errors! If you have retried several times, try a completely different approach.\n"
            )
            message_content = f"Call id: {self.tool_calls[0].id}\n" if self.tool_calls else ""
            message_content += error_message
            messages.append(
                ChatMessage(role=MessageRole.TOOL_RESPONSE, content=[{"type": "text", "text": message_content}])
            )

        return messages


@dataclass
class PlanningStep(MemoryStep):
    model_input_messages: list[ChatMessage]
    model_output_message: ChatMessage
    plan: str
    timing: Timing
    token_usage: TokenUsage | None = None

    def dict(self):
        return {
            "model_input_messages": [
                make_json_serializable(get_dict_from_nested_dataclasses(msg)) for msg in self.model_input_messages
            ],
            "model_output_message": make_json_serializable(
                get_dict_from_nested_dataclasses(self.model_output_message)
            ),
            "plan": self.plan,
            "timing": self.timing.dict(),
            "token_usage": asdict(self.token_usage) if self.token_usage else None,
        }

    def to_dict(self) -> "dict[str, Any]":
        # `model_input_messages` are left out: they duplicate the content of the previous steps
        return {
            "model_output_message": _chat_message_to_dict(self.model_output_message),
            "plan": self.plan,
            "timing": self.timing.dict(),
            "token_usage": self.token_usage.dict() if self.token_usage else None,
        }

    @classmethod
    def from_dict(cls, step_dict: "dict[str, Any]") -> "PlanningStep":
        return cls(
            model_input_messages=[],
            model_output_message=_chat_message_from_dict(step_dict["model_output_message"]),
            plan=step_dict["plan"],
            timing=_timing_from_dict(step_dict["timing"]),
            token_usage=_token_usage_from_dict(step_dict.get("token_usage")),
        )

    def to_messages(self, summary_mode: bool = False) -> list[ChatMessage]:
        if summary_mode:
            return []
        return [
            ChatMessage(role=MessageRole.ASSISTANT, content=[{"type": "text", "text": self.plan.strip()}]),
            ChatMessage(
                role=MessageRole.USER, content=[{"type": "text", "text": "Now proceed and carry out this plan."}]
            ),
            # This second message creates a role change to prevent models models from simply continuing the plan message
        ]


@dataclass
class TaskStep(MemoryStep):
    task: str
    task_images: list["PIL.Image.Image"] | None = None

    def to_messages(self, summary_mode: bool = False) -> list[ChatMessage]:
        content = [{"type": "text", "text": f"New task:\n{self.task}"}]
        if self.task_images:
            content.extend([{"type": "image", "image": image} for image in self.task_images])

        return [ChatMessage(role=MessageRole.USER, content=content)]


@dataclass
class SystemPromptStep(MemoryStep):
    system_prompt: str

    def to_messages(self, summary_mode: bool = False) -> list[ChatMessage]:
        if summary_mode:
            return []
        return [ChatMessage(role=MessageRole.SYSTEM, content=[{"type": "text", "text": self.system_prompt}])]


@dataclass
class FinalAnswerStep(MemoryStep):
    output: Any


# Memory step registry for deserialization: maps step class names to their actual classes.
MEMORY_STEP_REGISTRY: dict[str, Type[MemoryStep]] = {
    step_cls.__name__: step_cls for step_cls in (ActionStep, PlanningStep, TaskStep, SystemPromptStep, FinalAnswerStep)
}


class AgentMemory:
    """Memory for the agent, containing the system prompt and all steps taken by the agent.

    This class is used to store the agent's steps, including tasks, actions, and planning steps.
    It allows for resetting the memory, retrieving succinct or full step information, and replaying the agent's steps.

    Args:
        system_prompt (`str`): System prompt for the agent, which sets the context and instructions for the agent's behavior.

    **Attributes**:
        - **system_prompt** (`SystemPromptStep`) -- System prompt step for the agent.
        - **steps** (`list[TaskStep | ActionStep | PlanningStep]`) -- List of steps taken by the agent, which can include tasks, actions, and planning steps.
    """

    def __init__(self, system_prompt: str):
        self.system_prompt: SystemPromptStep = SystemPromptStep(system_prompt=system_prompt)
        self.steps: list[TaskStep | ActionStep | PlanningStep] = []

    def reset(self):
        """Reset the agent's memory, clearing all steps and keeping the system prompt."""
        self.steps = []

    def to_dict(self) -> dict[str, Any]:
        """Convert the memory to a JSON-serializable dictionary that can be restored with `from_dict`."""
        return {
            "system_prompt": self.system_prompt.system_prompt,
            "steps": [{"type": step.__class__.__name__, "data": step.to_dict()} for step in self.steps],
        }

    @classmethod
    def from_dict(cls, memory_dict: dict[str, Any]) -> "AgentMemory":
        """Create a memory from a dictionary generated by `to_dict`.

        Args:
            memory_dict (`dict[str, Any]`): Dictionary representation of the memory.

        Returns:
            `AgentMemory`: Memory holding the restored steps.
        """
        memory = cls(system_prompt=memory_dict["system_prompt"])
        for step_dict in memory_dict["steps"]:
            step_cls = MEMORY_STEP_REGISTRY.get(step_dict["type"])
            if step_cls is None:
                raise ValueError(
                    f"Unknown memory step class '{step_dict['type']}'. "
                    f"Supported steps: {', '.join(sorted(MEMORY_STEP_REGISTRY))}"
                )
            memory.steps.append(step_cls.from_dict(step_dict["data"]))
        return memory

    def get_succinct_steps(self) -> list[dict]:
        """Return a succinct representation of the agent's steps, excluding model input messages."""
        return [
            {key: value for key, value in step.dict().items() if key != "model_input_messages"} for step in self.steps
        ]

    def get_full_steps(self) -> list[dict]:
        """Return a full representation of the agent's steps, including model input messages."""
        if len(self.steps) == 0:
            return []
        return [step.dict() for step in self.steps]

    def replay(self, logger: AgentLogger, detailed: bool = False):
        """Prints a pretty replay of the agent's steps.

        Args:
            logger (`AgentLogger`): The logger to print replay logs to.
            detailed (`bool`, default `False`): If True, also displays the memory at each step. Defaults to False.
                Careful: will increase log length exponentially. Use only for debugging.
        """
        logger.console.log("Replaying the agent's steps:")
        logger.log_markdown(title="System prompt", content=self.system_prompt.system_prompt, level=LogLevel.ERROR)
        for step in self.steps:
            if isinstance(step, TaskStep):
                logger.log_task(step.task, "", level=LogLevel.ERROR)
            elif isinstance(step, ActionStep):
                logger.log_rule(f"Step {step.step_number}", level=LogLevel.ERROR)
                if detailed and step.model_input_messages is not None:
                    logger.log_messages(step.model_input_messages, level=LogLevel.ERROR)
                if step.model_output is not None:
                    logger.log_markdown(title="Agent output:", content=step.model_output, level=LogLevel.ERROR)
            elif isinstance(step, PlanningStep):
                logger.log_rule("Planning step", level=LogLevel.ERROR)
                if detailed and step.model_input_messages is not None:
                    logger.log_messages(step.model_input_messages, level=LogLevel.ERROR)
                logger.log_markdown(title="Agent output:", content=step.plan, level=LogLevel.ERROR)

    def return_full_code(self) -> str:
        """Returns all code actions from the agent's steps, concatenated as a single script."""
        return "\n\n".join(
            [step.code_action for step in self.steps if isinstance(step, ActionStep) and step.code_action is not None]
        )


class CallbackRegistry:
    """Registry for callbacks that are called at each step of the agent's execution.

    Callbacks are registered by passing a step class and a callback function.
    """

    def __init__(self):
        self._callbacks: dict[Type[MemoryStep], list[Callable]] = {}

    def register(self, step_cls: Type[MemoryStep], callback: Callable):
        """Register a callback for a step class.

        Args:
            step_cls (Type[MemoryStep]): Step class to register the callback for.
            callback (Callable): Callback function to register.
        """
        if step_cls not in self._callbacks:
            self._callbacks[step_cls] = []
        self._callbacks[step_cls].append(callback)

    def callback(self, memory_step, **kwargs):
        """Call callbacks registered for a step type.

        Args:
            memory_step (MemoryStep): Step to call the callbacks for.
            **kwargs: Additional arguments to pass to callbacks that accept them.
                Typically, includes the agent instance.

        Notes:
            For backwards compatibility, callbacks with a single parameter signature
            receive only the memory_step, while callbacks with multiple parameters
            receive both the memory_step and any additional kwargs.
        """
        # For compatibility with old callbacks that only take the step as an argument
        for cls in memory_step.__class__.__mro__:
            for cb in self._callbacks.get(cls, []):
                cb(memory_step) if len(inspect.signature(cb).parameters) == 1 else cb(memory_step, **kwargs)
